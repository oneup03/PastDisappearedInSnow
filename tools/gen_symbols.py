#!/usr/bin/env python3
"""Seed recomp/symbols.toml with every engine function in an episode image.

usage: tools/gen_symbols.py <image.sfc> [--out recomp/symbols.toml]

The engine's functions start with PHP/PHD/TSC/TCD and run in 16-bit modes, so the
prologue finds them, and analysis needs them as roots: control reaches them through
RTS dispatch it cannot follow. Addresses only, nothing from the ROM's content.
"""
import argparse
import pathlib

PROLOGUE = b"\x08\x0B\x3B\x5B"
CODE_END = 0x10000
BANK = 0xC0
VECTORS = {0xFF2C: "I_RESET", 0xFF4A: "I_NMI", 0xFF63: "I_IRQ"}


def find_functions(image):
    addrs, pos = [], image.find(PROLOGUE, 0, CODE_END)
    while pos != -1:
        addrs.append(pos)
        pos = image.find(PROLOGUE, pos + 1, CODE_END)
    return addrs


def render(addrs):
    out = ["# Generated by tools/gen_symbols.py. Addresses are for the Zenpen image.\n"]
    for addr, name in VECTORS.items():
        out.append(f'\n[[func]]\nname = "{name}"\naddr = "{addr:04x}"\nbank = 0\n'
                   f'emit = false\nnote = "Hardware vector"\n')
    for addr in addrs:
        out.append(f'\n[[func]]\nname = "F_{addr:04X}"\naddr = "{addr:04x}"\nbank = 0xc0\n'
                   f'emit = true\nentry_m = 0\nentry_x = 0\n')
    return "".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("image")
    ap.add_argument("--out", default="recomp/symbols.toml")
    args = ap.parse_args()
    addrs = find_functions(pathlib.Path(args.image).read_bytes())
    pathlib.Path(args.out).write_text(render(addrs))
    print(f"{args.out}: {len(addrs)} functions")


if __name__ == "__main__":
    main()
